export type StringKey = keyof typeof STRINGS;

/** Look up a string by key; unknown keys are a programming error, not a fallback. */
export function t(key: StringKey): string {
  return STRINGS[key];
}

/** A string with its `{name}` markers filled in; a marker with no value is left as written. */
export function fill(key: StringKey, values: Readonly<Record<string, string | number>>): string {
  return STRINGS[key].replace(/\{(\w+)\}/g, (marker: string, name: string) => {
    const value = values[name];
    return value === undefined ? marker : String(value);
  });
}
